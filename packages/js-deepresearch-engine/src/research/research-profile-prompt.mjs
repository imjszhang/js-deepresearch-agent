export function buildProfileUserMessage({
  query,
  literalHosts = [],
  userSlots = [],
  userRequiredHosts = [],
  evidenceScope = 'web',
  siteQueryMode = 'confirmed',
  retry = false,
} = {}) {
  const body = [
    'Compile an evidence contract from this query. Do not start a new research program.',
    '',
    `query: ${String(query || '').trim()}`,
    '',
    'alreadyExtracted:',
    `  literalHosts: ${JSON.stringify(unique(literalHosts))}`,
    `  userSlots: ${JSON.stringify(userSlots)}`,
    `  userRequiredHosts: ${JSON.stringify(unique(userRequiredHosts))}`,
    `  evidenceScope: ${evidenceScope || 'web'}`,
    `  siteQueryMode: ${siteQueryMode || 'confirmed'}`,
    '',
    'constraints:',
    '- If userSlots is non-empty, keep those questions unchanged and fill only empty fields',
    '- If evidenceScope is local, invent no web hosts and no primary_filing',
    '- requiredHosts ⊆ literalHosts ∪ userRequiredHosts',
    '- preferredHosts = first-party domains of entities found in the query, or the official hosting domain of an open-source artifact named in the query',
    '- Keep any opening premise inside the slot question',
    '- Every slot and every evidenceCriteria value must be entailed by the query',
    '- A supporting fact that helps close an existing slot is not a new slot',
    '- Do not add slots or source types because they are typical for the topic',
    '- Do not attach every run-level preference to every slot',
    '- Do not invent exchange, news, analyst, or paper hosts',
    '- requiredSourceTypes ∈ primary_filing|numeric',
    '- evidenceCriteria ∈ first_party|filing|numeric|user_named|mainstream_media',
  ].join('\n');
  if (!retry) return body;
  return `Previous profile JSON was truncated or invalid. Return complete compact JSON.\n\n${body}`;
}
